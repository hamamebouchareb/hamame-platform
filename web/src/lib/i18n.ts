// sizing note: bounded, reviewable, no framework dependency).
//
// Conventions:
// - Keys are namespaced per area: `nav.dashboard`, `settings.language.title`.
// - `fr` holds the exact pre-toggle French copy (moved verbatim, never
//   reworded during conversion — French rendering must stay byte-identical).
// - `en` is typed `Record<I18nKey, string>` so tsc fails the build if any key
//   lacks an English translation. Add both languages together, always.
// - Dynamic values use `{name}` templates + the `vars` argument; plural forms
//   are separate keys selected by the caller (French and English pluralize
//   differently — no shared plural logic).
// - NOT translated here: proper nouns (wilaya names, faculty/year labels from
//   the API), currency codes ("DZD"), brand ("Hamame"), and backend content
//   (emails/SMS, question bodies, lesson content stay French).

export type UiLanguage = "fr" | "en";

export const DEFAULT_LANGUAGE: UiLanguage = "fr";

export const LANGUAGE_STORAGE_KEY = "hamame_lang";

export function isUiLanguage(value: unknown): value is UiLanguage {
  return value === "fr" || value === "en";
}

// Locale for Intl formatters. French keeps the exact pre-toggle behavior
// ("fr-DZ" everywhere it was used); English uses "en".
export function localeFor(lang: UiLanguage): string {
  return lang === "en" ? "en" : "fr-DZ";
}

