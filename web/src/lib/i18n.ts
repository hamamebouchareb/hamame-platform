export function translate(
  lang: UiLanguage,
  key: I18nKey,
  vars?: Record<string, string | number | null | undefined>
): string {
  const template = lang === "en" ? en[key] : fr[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    vars[name] == null ? match : String(vars[name])
  );
}

/**
 * Localizes an ExamReadiness label from the API ("Exam ready" | "On track" |
 * "Needs work"). Shared by every surface rendering readiness — do not
 * re-implement per page.
 */
export function readinessLabel(lang: UiLanguage, label: string | null): string {
  switch (label) {
    case "Exam ready":
      return translate(lang, "readiness.examReady");
    case "On track":
      return translate(lang, "readiness.onTrack");
    case "Needs work":
      return translate(lang, "readiness.needsWork");
    default:
      return translate(lang, "readiness.unknown");
  }
}
